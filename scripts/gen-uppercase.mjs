// Writes src/upper_table.inc: every code point JavaScript's String.prototype
// toUpperCase changes, and what it becomes (locale-independent full case
// mapping, as the reference SDK upper-cases an entered licence key).
//
//   node scripts/gen-uppercase.mjs
//
// The table is what the Node running this answers (its ICU's Unicode version).
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const rows = []
let widest = 0
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) continue
  const from = String.fromCodePoint(cp)
  const to = from.toUpperCase()
  if (to === from) continue
  const points = [...to].map((c) => c.codePointAt(0))
  widest = Math.max(widest, points.length)
  rows.push([cp, points])
}
if (widest > 3) throw new Error(`an upper-case mapping of ${widest} code points does not fit the table`)

const hex = (n) => `0x${n.toString(16).toUpperCase()}`
const lines = rows.map(([cp, points]) => {
  const padded = [...points, 0, 0, 0].slice(0, 3)
  return `    {${hex(cp)}, {${padded.map(hex).join(', ')}}},`
})
const out = `// Generated by scripts/gen-uppercase.mjs from Node ${process.version}'s String.prototype.toUpperCase.
// Do not edit by hand. ${rows.length} code points, sorted.
// clang-format off
${lines.join('\n')}
// clang-format on
`
const target = fileURLToPath(new URL('../src/upper_table.inc', import.meta.url))
writeFileSync(target, out)
console.log(`wrote ${target}: ${rows.length} mappings`)
